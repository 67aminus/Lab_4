/*Ввести число остановок n (1..20) и вместимость автобуса C (1..100).
В цикле for для каждой остановки ввести два числа: сколько пассажиров вышло и сколько вошло (оба неотрицательны).
Изначально автобус пуст. Сначала пассажиры выходят, затем входят. 
Если вышло больше, чем было внутри, или после входа число пассажиров превышает C, 
вывести «Ошибка данных» и завершить программу. 
Иначе вывести заполненность после каждой остановки и её максимальное значение за маршрут.
*/
#include <iostream>

using namespace std;
int main() {
	int n;
	int C;
	int exited;
	int entered;
	int inside = 0;
	int maxInside = 0;

	cout << "Введите число остановок (1..20): ";
	cin >> n;
	cout << "Введите вместимость автобуса (1..100): ";
	cin >> C;
	if (n <= 0 || n > 20 || C <= 0 || C > 100) {
		cout << "Ошибка данных"; 
		return 0;
}
	for (int i = 0; i < n; i++) {
		cout << "Остановка " << (i + 1) << ": вышло и вошло: ";
		cin >> exited;
		cin >> entered;

		if (exited < 0 || entered < 0 || exited > inside) {
			cout << "Ошибка данных";
			return 0;
		}
		inside = inside + entered - exited; 
		if (inside > C) {
			cout << "Ошибка данных";
			return 0;
		}
		cout << "Заполненность после остановки " << (i + 1) << ": " << inside << "\n";

		if (inside > maxInside)	maxInside = inside;
	}
	cout << "Максимальная заполненность за маршрут: " << maxInside;
	return 0;
}