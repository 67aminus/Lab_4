/*Ввести N (1..100) — число мест в зале.
Затем циклом while принимать номера занятых мест до 0.
Номера вне диапазона 1..N (кроме 0) игнорировать.
Найти количество принятых записей и сколько раз два соседних корректных ввода называли одно и то же место.
Уникальность всех мест проверять не требуется;
некорректный ввод не разрывает сравнение соседних корректных записей.*/
#include <iostream>

using namespace std;
int main() {
	int N;
	int taken;
	int quantity = 0;
	int check = 0;
	int repeated = 0;

	cout << "Введите число мест в зале (1..100): ";
	cin >> N;
	if (N > 100 || N < 1) {
		cout << "Ошибка данных";
		return 0;
	}
	cout << "Введите номер занятого места: ";
	cin >> taken;
	if (taken != 0) {
		if (taken <= N && taken >= 1) quantity++;
		while (taken != 0) {
			if (taken <= N && taken >= 1) check = taken;
			cout << "Введите номер занятого места: ";
			cin >> taken;
			if (taken <= N && taken >= 1) {
				if (check == taken) repeated++;
				quantity++;
			}
		}
	}
	cout << "Количество принятых записей: " << quantity << endl;
	cout << "Количество раз, когда два соседних корректных ввода называли одно и то же место: " << repeated;
	return 0;
}